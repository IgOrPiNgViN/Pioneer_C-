/*
Упражнение 4: Обращение массива
Создай программу для обращения массива (первый элемент становится последним и наоборот):
*/

void exercise4() {
    int arr[8] = {1, 2, 3, 4, 5, 6, 7, 8};
    
    cout << "Исходный массив: ";
    for (int i = 0; i < 8; i++) {
        cout << arr[i] << " ";
    }
    cout << endl;
    
    // Обращение массива
    int start = 0;
    int end = 8 - 1;
    
    while (start < end) {
        // Обмен элементов
        int temp = arr[start];
        arr[start] = arr[end];
        arr[end] = temp;
        
        start++;
        end--;
    }
    
    cout << "Обращенный массив: ";
    for (int i = 0; i < 8; i++) {
        cout << arr[i] << " ";
    }
    cout << endl;
}

/*
Упражнение 5: Сортировка пузырьком
Создай программу для сортировки массива методом пузырька:
*/

void exercise5() {
    int arr[6] = {64, 34, 25, 12, 22, 11};
    
    cout << "Исходный массив: ";
    for (int i = 0; i < 6; i++) {
        cout << arr[i] << " ";
    }
    cout << endl;
    
    // Сортировка пузырьком
    for (int i = 0; i < 6 - 1; i++) {
        for (int j = 0; j < 6 - i - 1; j++) {
            if (arr[j] > arr[j + 1]) {
                // Обмен элементов
                int temp = arr[j];
                arr[j] = arr[j + 1];
                arr[j + 1] = temp;
            }
        }
    }
    
    cout << "Отсортированный массив: ";
    for (int i = 0; i < 6; i++) {
        cout << arr[i] << " ";
    }
    cout << endl;
}

/*
Упражнение 6: Сортировка выбором + бинарный поиск
1) Отсортируй массив выбором
2) Найди число бинарным поиском
*/

void exercise6() {
    int arr[8] = {42, 7, 19, 3, 88, 15, 27, 61};
    int n = 8;
    
    cout << "Исходный: ";
    for (int i = 0; i < n; i++) cout << arr[i] << " ";
    cout << endl;
    
    // Сортировка выбором
    for (int i = 0; i < n - 1; i++) {
        int minIdx = i;
        for (int j = i + 1; j < n; j++) {
            if (arr[j] < arr[minIdx]) minIdx = j;
        }
        int t = arr[i];
        arr[i] = arr[minIdx];
        arr[minIdx] = t;
    }
    
    cout << "После selection sort: ";
    for (int i = 0; i < n; i++) cout << arr[i] << " ";
    cout << endl;
    
    int target;
    cout << "Число для бинарного поиска: ";
    cin >> target;
    
    int left = 0, right = n - 1;
    int found = -1;
    while (left <= right) {
        int mid = (left + right) / 2;
        if (arr[mid] == target) {
            found = mid;
            break;
        } else if (arr[mid] < target) {
            left = mid + 1;
        } else {
            right = mid - 1;
        }
    }
    
    if (found != -1) {
        cout << "Найдено на позиции " << found << endl;
    } else {
        cout << "Не найдено" << endl;
    }
}

