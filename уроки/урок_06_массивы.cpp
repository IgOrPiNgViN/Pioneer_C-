    int arr1[5] = {1, 2, 3, 4, 5};  // полная инициализация
    cout << "arr1 (полная): ";
    for (int i = 0; i < 5; i++) cout << arr1[i] << " ";
    cout << endl;
    
    int arr2[5] = {1, 2};  // частичная (остальные = 0)
    cout << "arr2 (частичная): ";
    for (int i = 0; i < 5; i++) cout << arr2[i] << " ";
    cout << endl;
    
    int arr3[] = {10, 20, 30};  // автоматический размер
    cout << "arr3 (авторазмер): ";
